COMPARED_SUFFIX = (".msh",)
# Leaves that say which build wrote the file, not what it computed: compared with the build that runs, not with the
# recorded string, so that a version bump changes no baseline. results.json carries the package version.
IDENTITY = {"results.json": {"/version": "version"}}
MASKED = "<masked>"  # what a masked value is replaced by in the text of a JSON file
# environment variables that change what the mesher does and that no run of the harness may inherit
ENV_CLEARED = ("AXMP_MESHER_ASLR",)
ENV_FIXED = {"OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1", "VECLIB_MAXIMUM_THREADS": "1"}
# An OpenBLAS built for several processors picks its kernels from the processor it starts on, and the kernels round
# differently: the same build gave other last digits in the electrostatic capacitance figures on a processor with
# AVX-512 (kernel SkylakeX) than on one without (Haswell, Zen), which made the reference platform's bytes depend on
# the machine the hosted image happened to run on. Every x86_64 run is therefore given one kernel all of them have.
BLAS_KERNEL_X86_64 = "HASWELL"


# Pins of the particle-transport programs (Geant4, Pythia, HepMC3 and Xerces-C, which only a Geant4 with GDML needs).
# No build that G0 compares links them, so a line naming one is left out of `dependency_pins`: adding or changing such
# a pin must not invalidate the recorded fingerprints. The development gate filters its stack keys the same way.
TRANSPORT_PINS = re.compile(rb"geant4|pythia|hepmc|xerces", re.IGNORECASE)


def dependency_pins_digest(pins: Path) -> str:
    """sha256 of the pins file without its transport-only lines, byte for byte otherwise: a file without such lines
    hashes exactly as the whole file does."""
    kept = [l for l in re.findall(rb"[^\n]*\n|[^\n]+", pins.read_bytes()) if not TRANSPORT_PINS.search(l)]
    return hashlib.sha256(b"".join(kept)).hexdigest()


def fixed_environment() -> dict:
    """The environment variables every run of the harness is given: one thread, and on x86_64 one BLAS kernel."""
    env = dict(ENV_FIXED)
    if platform.machine().lower() in ("x86_64", "amd64"):
        env["OPENBLAS_CORETYPE"] = BLAS_KERNEL_X86_64
    return env
# Tier C compares every figure to the reference platform's value relative to that value alone: there is no shared scale
# (a scale taken from the largest figure of a file lets one large number, such as the 1e30 that stands for "no
# margin", hide every small one).
TINY = 1e-300
# lowest tier-C tolerance: the relative residual to which the engine's direct solves are gated (direct_tol = 1e-10,
# cpp/include/axionmultiphysics/fluids/stokes.hpp); a measured spread below it is round-off
TOL_FLOOR = 1e-10
TOL_FACTOR = 10.0  # asserted tolerance = TOL_FACTOR x the largest measured spread
# Ceiling of the spread that counts as platform round-off: 1e-7, the largest of the ceilings this project gives its
# exactness tests (that of a Newton solve). A quantity that spreads more than this between platforms differs because
# the problem solved differs (another mesh from another mesher build, a value near zero on a symmetric field). It is
# listed apart from the round-off class (`over_ceiling`, with its spread and the platform) and asserted there at
# TOL_FACTOR x its measured spread: a coarse check, which fails for a change by a factor of two and says nothing
# below the size of the spread.
SPREAD_CEILING = 1e-7
# The largest spread a figure of the over-ceiling class may have. On a platform where the figure is off the reference
# by the spread d, the value halved is off by at least 0.5 - d/2 and the value doubled by more, so a tolerance of
# TOL_FACTOR x d fails both as long as it is below 0.5 - d/2: a spread below 0.5 / (TOL_FACTOR + 0.5), which is
# 0.0476 for TOL_FACTOR = 10. A figure that spreads more (a round-off residual, a figure that is zero on the reference,
# a sum that nearly cancels) cannot be given a tolerance that still fails a factor of two, and is listed as unasserted.
WIDE_TOLERANCE_LIMIT = 0.5
WIDE_SPREAD_CEILING = WIDE_TOLERANCE_LIMIT / (TOL_FACTOR + 0.5)
# quantities that are sizes of the mesh or of its linear systems: not asserted in tier C, whatever their spread
MESH_SIZED = re.compile(r"^(dofs|free_dofs|reduced_unknowns|unknowns|equations|nodes|elements(_\dd)?|nonzeros(_\w+)?|"
                        r"cells|faces|samples|n_points|\w+_elements)$")
MAX_ARRAY_FIGURES = 64
# The leaves of a JSON file that a tier-B mask may name: only timings and run identity. The names are matched whole
# (a substring match would take `newton_update` for a date and `q_wall` for a wall time), and a `_s` suffix alone is a
# physical time (`tau_s`), so it counts only directly under a `timing` object, or as one of the three per-solve
# timings the 3D solver logs, by exact name, in an item of `/solver/solves`.
MASKABLE_NAME = re.compile(r"^((\w+_)?seconds|hostname|pid|timestamp)$")
MASKABLE_TIMING = re.compile(r"^\w+_s$")
MASKABLE_SOLVE_LOG = ("clean_s", "setup_s", "solve_s")
ABSENT = "<absent>"  # stands for a leaf that one of two documents does not have


def maskable(pointer: str) -> bool:
    """Whether the leaf at `pointer` (or at a pattern of one) is a timing or run identity by its name."""
    tokens = pointer.split("/")
    last = tokens[-1]
    if MASKABLE_NAME.match(last):
        return True
    if len(tokens) >= 2 and tokens[-2] == "timing" and bool(MASKABLE_TIMING.match(last)):
        return True
    return (last in MASKABLE_SOLVE_LOG and len(tokens) >= 4 and tokens[-4:-2] == ["solver", "solves"]
            and (tokens[-2] == "*" or tokens[-2].isdigit()))


