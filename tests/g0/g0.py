def _sha(data: bytes | str) -> str:
    return hashlib.sha256(data if isinstance(data, bytes) else data.encode()).hexdigest()


def run_entry(item: dict, work: Path) -> dict:
    """Run one tier-B entry into `work`; return what was observed (unmasked)."""
    norm = Norm(work)
    exe = axmp_exe()
    path = item.get("design")
    if "template" in item:
        src = work.parent / f"{_safe(item['id'])}-design.json"
        src.write_text(_run([exe, "template", item["template"]])["stdout"])
        path = str(src)
    op = item.get("op", "solve")
    cmd = launcher() + [exe, op, path, "-o", str(work)] + list(item.get("args", []))
    r = _run(cmd, timeout=item.get("timeout", 1800))
    files, file_set = {}, []
    if work.is_dir():
        file_set = sorted(f.relative_to(work).as_posix() for f in work.rglob("*") if f.is_file())
        for f in sorted(work.iterdir()):
            if not f.is_file() or not (f.name in COMPARED or f.suffix in COMPARED_SUFFIX):
                continue
            raw = f.read_bytes()
            if f.suffix == ".json":
                text = norm(raw.decode("utf-8"))
                files[f.name] = {"kind": "json", "doc": json.loads(text), "text": text, "sha256": _sha(text)}
            else:
                try:
                    text = norm(raw.decode("utf-8"))
                    files[f.name] = {"kind": "text", "sha256": _sha(text), "bytes": len(text)}
                except UnicodeDecodeError:
                    files[f.name] = {"kind": "binary", "sha256": _sha(raw), "bytes": len(raw)}
    return {"status": r["status"], "stdout": norm(r["stdout"]), "files": files, "file_set": file_set}


PROCESS_FLAGS = ("high_order_canonical", "address_randomization")


def canonical_flags(files: dict) -> dict:
    """What the mesher reports of the process that made each mesh of the run: `high_order_canonical` (the curved-mesh
    process) and `address_randomization` (the mesher switches it off for itself on Linux and says so)."""
    out = {}
    for name, f in files.items():
        if f["kind"] != "json":
            continue
        for ptr, v in leaves(f["doc"]):
            if ptr.rsplit("/", 1)[-1] in PROCESS_FLAGS:
                out[f"{name}{ptr}"] = v
    return out


def process_not_pinned(flags: dict) -> list[str]:
    """The mesher-process flags of a run that say its mesh was not made in the reproducible process: a curved mesh
    outside the canonical process, or a mesher that ran with address-space randomisation on."""
    out = []
    for k, v in sorted(flags.items()):
        name = k.rsplit("/", 1)[-1]
        if (name == "high_order_canonical" and v not in (True, "on", "n/a")) or (name == "address_randomization" and v == "on"):
            out.append(f"{k} = {v!r}")
    return out


def tier_b_masks(r1: dict, r2: dict) -> tuple[list[dict], list[str]]:
    """From two runs of one entry: mask entries for differing JSON leaves, and the files that cannot be masked."""
    masks, unmaskable = [], []
    if r1["status"] != r2["status"]:
        unmaskable.append("exit status")
    if r1["stdout"] != r2["stdout"]:
        unmaskable.append("stdout")
    if set(r1["files"]) != set(r2["files"]) or r1.get("file_set") != r2.get("file_set"):
        unmaskable.append("file set")
    for name in sorted(set(r1["files"]) & set(r2["files"])):
        a, b = r1["files"][name], r2["files"][name]
        if a["sha256"] == b["sha256"]:
            continue
        if a["kind"] != "json":
            unmaskable.append(name)
            continue
        da, db = dict(leaves(a["doc"])), dict(leaves(b["doc"]))
        if set(da) != set(db):
            unmaskable.append(f"{name} (key set)")
            continue
        seen = set()
        for ptr in sorted(da):
            if da[ptr] != db[ptr] and not (isinstance(da[ptr], float) and math.isnan(da[ptr]) and math.isnan(db[ptr])):
                pat = _pattern(ptr)
                if pat not in seen:
                    seen.add(pat)
                    masks.append({"file": name, "pointer": pat, "reason": _classify(ptr, da[ptr])})
    return masks, unmaskable


def baseline_entry(obs: dict, patterns_by_file: dict) -> dict:
    """The stored form of one tier-B observation. Every compared file is stored as the hash of its text; for a JSON
    file that is the text with the masked values, and the build-identity leaves, blanked in place (`masked_text`), so
    the whitespace, the spelling of every unmasked number and the order of the keys are compared too. The hash of the
    layout (keys in file order, list lengths) is kept beside it only to say which kind of difference was found. The
    names of all files of the run directory are stored, whether their content is compared or not."""
    files = {}
    for name, f in obs["files"].items():
        rec = {"kind": f["kind"]}
        if f["kind"] == "json":
            pats = list(patterns_by_file.get(name, [])) + identity_patterns(name)
            rec["layout_sha256"] = _sha("\n".join(layout(f["doc"])))
            rec["sha256"] = _sha(masked_text(f["text"], pats))
            rec["masked_leaves"] = sum(1 for ptr, _ in leaves(f["doc"]) if any(_matches(p, ptr) for p in pats))
        else:
            rec["sha256"], rec["bytes"] = f["sha256"], f["bytes"]
        files[name] = rec
    return {"status": obs["status"], "stdout_sha256": _sha(obs["stdout"]), "files": files,
            "file_set": list(obs.get("file_set", [])), "mesher_process": canonical_flags(obs["files"])}


def tier_b_compare(entry_id: str, base: dict, obs: dict, patterns_by_file: dict, allowed_new_files=(),
                   recorded_leaves: dict | None = None) -> list[str]:
    """`recorded_leaves` ({"figures": ..., "discrete": ...} of the entry, from the platform's figures record) only
    serves to name the leaves of a results.json that differs."""
    now = baseline_entry(obs, patterns_by_file)
    diffs = []
    if now["status"] != base["status"]:
        diffs.append(f"tier B: {entry_id}: exit status {base['status']} -> {now['status']}")
    if now["stdout_sha256"] != base["stdout_sha256"]:
        diffs.append(f"tier B: {entry_id}: stdout differs")
    gone = sorted(set(base.get("file_set", [])) - set(now["file_set"]))
    new = sorted(set(now["file_set"]) - set(base.get("file_set", [])) - set(allowed_new_files))
    if gone or new:
        diffs.append(f"tier B: {entry_id}: the files of the run directory differ: no longer written {gone}, new {new} "
                     "(a declared new file goes on the manifest's `allowed_new_files` until the baseline is recorded again)")
    for name in sorted(set(base["files"]) | set(now["files"])):
        a, b = base["files"].get(name), now["files"].get(name)
        if a is None or b is None:
            if b is not None and name in allowed_new_files:
                continue
            diffs.append(f"tier B: {entry_id}: {name} is {'new' if a is None else 'missing'}")
            continue
        if a.get("layout_sha256") != b.get("layout_sha256"):
            diffs.append(f"tier B: {entry_id}: {name}: the keys, their order or the list lengths differ")
        if a["sha256"] != b["sha256"]:
            detail = ""
            if name == "results.json" and recorded_leaves is not None:
                pats = list(patterns_by_file.get(name, [])) + identity_patterns(name)
                found = _leaf_diffs(recorded_leaves, obs["files"][name]["doc"], pats)[:10]
                detail = "\n" + "\n".join(found or ["    (no recorded figure or non-numeric leaf differs: the difference is "
                                                     "in an array of more than 64 numbers, in the spelling of a number "
                                                     "or in the whitespace)"])
            diffs.append(f"tier B: {entry_id}: {name} differs{detail}")
    return diffs


def _leaf_diffs(recorded: dict, doc, pats) -> list[str]:
    da = {**recorded.get("figures", {}), **_no_identity(recorded.get("discrete", {}))}
    db = {**figures(doc, pats), **discrete(doc, pats)}
    return [f"    {p}: {da.get(p, ABSENT)!r} -> {db.get(p, ABSENT)!r}" for p in sorted(set(da) | set(db))
            if da.get(p, ABSENT) != db.get(p, ABSENT)]


def figures(doc, pats=()) -> dict:
    """Scalar numeric leaves of a results document (small arrays element by element), masked leaves dropped."""
    out = {}
    doc = apply_mask(doc, list(pats))

    def walk(x, ptr):
        if isinstance(x, dict):
            for k in sorted(x):
                walk(x[k], f"{ptr}/{k}")
        elif isinstance(x, list):
            if len(x) <= MAX_ARRAY_FIGURES:
                for i, v in enumerate(x):
                    walk(v, f"{ptr}/{i}")
        elif isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x):
            out[ptr] = float(x)
    walk(doc, "")
    return out


def discrete(doc, pats=()) -> dict:
    """Every leaf of a results document that is not a finite number: the booleans (the verdicts of the physics checks),
    the strings, the nulls and the non-finite numbers (as text), masked leaves dropped. They need no tolerance."""
    out = {}
    for ptr, v in leaves(apply_mask(doc, list(pats))):
        if isinstance(v, bool) or v is None or isinstance(v, str):
            out[ptr] = v
        elif isinstance(v, float) and not math.isfinite(v):
            out[ptr] = repr(v)
    return out


def _layout_pointer(item: str) -> str:
    return re.sub(r"\[\d+\]$", "", item)


def layout_difference(ref: list[str], now: list[str]) -> list[str]:
    """The pointers at which two layouts differ (a key that only one has, a list of another length); "*" when the same
    keys come in another order."""
    a, b = set(ref), set(now)
    out = sorted({_layout_pointer(x) for x in a ^ b})
    drop = set(out)
    if [x for x in ref if _layout_pointer(x) not in drop] != [x for x in now if _layout_pointer(x) not in drop]:
        out.append("*")
    return out


def discrete_difference(ref: dict, now: dict) -> dict:
    """{pointer: [reference value, value here]} of the non-numeric leaves that differ; ABSENT where one side has none."""
    return {p: [ref.get(p, ABSENT), now.get(p, ABSENT)] for p in sorted(set(ref) | set(now))
            if ref.get(p, ABSENT) != now.get(p, ABSENT) or type(ref.get(p, ABSENT)) is not type(now.get(p, ABSENT))}


def rel_diff(ref: float, val: float) -> float:
    """Relative to the reference value alone (a reference of zero gives infinity unless the value is zero too)."""
    return abs(val - ref) / max(abs(ref), TINY)


def mesh_sized(ptr: str) -> bool:
    return bool(MESH_SIZED.match(ptr.rsplit("/", 1)[-1]))


def tier_c_exact(entry_id: str, ref_discrete: dict, ref_layout: list[str], doc, pats: list[str],
                 unasserted_discrete=(), unasserted_layout=()) -> tuple[list[str], int]:
    """The part of tier C that needs no tolerance: every non-numeric leaf of results.json equal to the reference
    platform's, and the same layout, outside the pointers measured to differ on this platform. Returns the differences
    and the number of leaves compared."""
    diffs = []
    skip = set(unasserted_discrete)
    pats = list(pats) + identity_patterns("results.json")
    ref_discrete = _no_identity(ref_discrete)
    d = {p: v for p, v in discrete_difference(ref_discrete, discrete(doc, pats)).items() if p not in skip}
    for p, (a, b) in list(d.items())[:20]:
        diffs.append(f"tier C: {entry_id}: {p}: {a!r} -> {b!r} (not a number: compared exactly)")
    if len(d) > 20:
        diffs.append(f"tier C: {entry_id}: and {len(d) - 20} more non-numeric leaves differ")
    if "*" not in unasserted_layout:
        drop = set(unasserted_layout)
        now_layout = layout(doc)
        moved = [p for p in layout_difference(ref_layout, now_layout) if p not in drop]
        a = [x for x in ref_layout if _layout_pointer(x) not in drop]
        b = [x for x in now_layout if _layout_pointer(x) not in drop]
        if moved or a != b:
            diffs.append(f"tier C: {entry_id}: the keys, their order or the list lengths of results.json differ at "
                         f"{(moved or ['(order)'])[:8]}")
    return diffs, len(set(ref_discrete) - skip)


def tier_c_compare(entry_id: str, ref: dict, obs: dict, pats: list[str], tol: dict,
                   unasserted=()) -> tuple[list[str], int, int, int]:
    """`ref`: the reference platform's figures of the entry; `obs`: a run here. Returns the differences, the number of
    figures asserted, the number left out (mesh-sized, or listed as unasserted) and the number this platform has no
    measurement of. `tol` holds the figures whose spread was measured here: a figure it does not name was never
    measured on this platform, so it is **not compared** and is counted and reported instead. Asserting it at the floor
    would be an invented number, for the same reason that a whole entry without a measurement is pending here
    (docs/developer/g0.md); the reference platform's tier B is what holds such a figure. The non-numeric leaves and the
    layout are compared by `tier_c_exact`."""
    diffs = []
    if "results.json" not in obs["files"]:
        return [f"tier C: {entry_id}: no results.json (exit status {obs['status']})"], 0, 0, 0
    now = figures(obs["files"]["results.json"]["doc"], pats)
    if set(ref) != set(now):
        diffs.append(f"tier C: {entry_id}: the set of figures differs: only in baseline {sorted(set(ref) - set(now))[:5]}, "
                     f"only here {sorted(set(now) - set(ref))[:5]}")
    asserted = left_out = unmeasured = 0
    for ptr in sorted(set(ref) & set(now)):
        if ptr in unasserted or mesh_sized(ptr):
            left_out += 1
            continue
        if ptr not in tol:
            unmeasured += 1
            continue
        asserted += 1
        d = rel_diff(ref[ptr], now[ptr])
        t = tol[ptr]
        if d > t:
            diffs.append(f"tier C: {entry_id}: {ptr}: {ref[ptr]!r} -> {now[ptr]!r}, relative difference {d:.3g} > tolerance {t:.3g}")
    return diffs, asserted, left_out, unmeasured


# ------------------------------------------------------------------------------------------------- commands
def _write(path: Path, doc) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n", "utf-8")


def _read(path: Path):
    return json.loads(path.read_text("utf-8")) if path.is_file() else None


def _entries(tier_b: list[dict], names: set[str] | None) -> list[dict]:
    """The tier-B entries to run here: those named, and those this build can run (an entry that `requires_engine_3d`
    is not run by a sequential build, which refuses 3D designs; tier A holds its refusal text)."""
    mpi = build_kind() == "mpi"
    return [e for e in tier_b if (names is None or e["id"] in names) and (mpi or not e.get("requires_engine_3d"))]


def _only(args, manifest: dict) -> tuple[set[str] | None, str]:
    """The entry ids of --only, and why they cannot be used (a name that is no entry of the manifest)."""
    if not args.only:
        return None, ""
    names = {n for n in args.only.split(",") if n}
    unknown = sorted(names - {e["id"] for e in manifest["tier_b"]})
    if unknown or not names:
        return names, f"--only names no tier-B entry of the manifest: {unknown or args.only!r}"
    return names, ""


def cmd_fingerprint(args) -> int:
    print(json.dumps(fingerprint(), indent=1, sort_keys=True))
    return 0


def cmd_record(args) -> int:
    fp = fingerprint()
    key = fp["platform"]
    out = Path(args.out) if args.out else G0 / "baseline" / key
    spread = Path(args.spread) if args.spread else G0 / "spread" / f"{key}.json"
    manifest = load_manifest()
    reference = key == REFERENCE
    text_only = key in TIER_A_PLATFORMS
    names, bad = _only(args, manifest)
    if bad:
        print("g0: " + bad)
        return 2
    if names and not (args.out and args.spread):
        print("g0: record --only writes a record of some entries only, which must not replace a baseline: give --out and "
              "--spread in a scratch directory")
        return 2
    why = refuse_record(fp, key, args.repin)
    if why:
        print("g0: record refused: " + why)
        return 4
    tmp = Path(tempfile.mkdtemp(prefix="g0-"))
    try:
        # tier A twice; the second time with a longer path (a different output directory)
        a1 = tier_a(_mk(tmp / "a1"))
        a2 = tier_a(_mk(tmp / ("a2-" + "x" * 37)))
        masks = {"platform": key, "tier_a": tier_a_masks(a1, a2), "tier_b": [], "tier_c_by_name": []}
        print(f"tier A: {len(a1['designs'])} designs, {len(a1['corpus'])} corpus documents, "
              f"{len(masks['tier_a'])} differences between the two runs")
        # tier B twice on every platform that is compared beyond tier A, the second time in a directory of another path
        # length: what is the same in both runs is this platform's own record. An entry that is not the same outside
        # its timings has none, and its figures are no record either, because one of two values that disagree is not a
        # reference: on the reference platform nothing of it is written, and on any other both runs are kept, so that
        # its spread from the reference is measured over both
        runs, second_runs, timing_pats, tier_b, wrong_identity = {}, {}, {}, {}, []
        for e in ([] if text_only else _entries(manifest["tier_b"], names)):
            o1 = run_entry(e, _mk(tmp / "b1" / e["id"]))
            o2 = run_entry(e, _mk(tmp / ("b2-" + "y" * 29) / e["id"]))
            wrong_identity += identity_diffs(e["id"], o1)
            m, unmask = tier_b_masks(o1, o2)
            physics = sorted({f"{x['file']} {x['pointer']}" for x in m if x["reason"] != TIMING})
            off = process_not_pinned(canonical_flags(o1["files"]))
            print(f"  {e['id']}: exit status {o1['status']}, {len(m)} masks"
                  + (f", NOT reproducible: {(unmask + physics + off)[:6]}" if unmask or physics or off else ""), flush=True)
            if unmask or physics or off:
                why = "; ".join(unmask + [f"{x} differs between two runs" for x in physics]
                                + [f"mesher process {x}" for x in off])
                masks["tier_c_by_name"].append({"entry": e["id"], "reason": "not reproducible on this platform: " + why})
                if not reference:
                    runs[e["id"]], second_runs[e["id"]] = o1, o2
                    # it has no tier-B record, hence no masks: its timings are dropped from the figures by this list
                    timing_pats[e["id"]] = [x["pointer"] for x in m if x["file"] == "results.json" and x["reason"] == TIMING]
                continue
            runs[e["id"]] = o1
            pats = {}
            for x in m:
                masks["tier_b"].append({"entry": e["id"], **x})
                pats.setdefault(x["file"], []).append(x["pointer"])
            tier_b[e["id"]] = baseline_entry(o1, pats)
        if wrong_identity:
            print("g0: record refused: " + "; ".join(wrong_identity))
            return 5
        if refuse_new_masks(masks, key, args):
            return 3
        if text_only:
            print(f"{key} is compared at tier A only: no solve was run, and the text record alone is written")
        else:
            _write(out / "tierB.json", {"format": FORMAT_B, "platform": key, "entries": tier_b})
            if reference:
                _write(out / "figures.json", {"format": FORMAT, "platform": key, **_figures_of(runs, masks)})
                # the reference platform's figures are what everything is compared with, not a spread: a spread file
                # left over from when this platform was compared with another reference would make it its own tier-C
                # family
                if not args.out and spread.is_file():
                    spread.unlink()
                    print(f"removed {spread}: the reference platform's figures are in {out / 'figures.json'}")
            else:
                doc = {"format": FORMAT, "platform": key, "fingerprint": fp["compared"],
                       **_figures_of(runs, masks, timing_pats)}
                if second_runs:
                    doc["second_run"] = _figures_of(second_runs, masks, timing_pats)
                _write(spread, doc)
        _write(out / "tierA.json", {"format": FORMAT, "platform": key, **a1})
        _write(out / "fingerprint.json", fp)
        _write(out / "masks.json", masks)
        print(f"recorded {key} into {out}")
        for m in masks["tier_c_by_name"]:
            print(f"g0: NO RECORD of {m['entry']} on {key}: {m['reason']}. "
                  + ("Nothing of it was written: tier C does not run on the reference platform and no platform can be "
                     "compared with one of two values that disagree, so the entry is pending and `check` fails for it "
                     "until it is reproducible here or off the manifest" if reference else
                     "It has no tier-B record here; tier C compares it with the reference platform's record, to "
                     "tolerances measured over both of its runs (`second_run` in the spread file)"))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return 0


# Where the processor model is recorded but pins nothing: the platforms no record of bytes is compared on. A hosted
# runner is given whichever model its fleet has that day, which is nobody's choice and no change of the platform; a
# `record` that refused for it would succeed or not by the draw, and `--repin`, which exists for an argued re-recording
# of a platform that moved, would become the habit. On the reference platform the model is the pin, and on a host with
# a name of its own it is part of what its own tier-B record is compared under, so there it still refuses.
CPU_PINS_NOTHING = (*TIER_AC_PLATFORMS, *TIER_A_PLATFORMS)


def refuse_record(fp: dict, key: str, repin: bool) -> str:
    """Why `record` must not write this platform's baseline from this host (empty when it may). The platform key says
    only the operating system, the machine and the build kind, so another host can have the key of a recorded platform,
    the reference's included: what decides is the fingerprint. `repin` is the argued re-recording of a platform that
    moved (docs/developer/g0.md); it never covers a reference fingerprint without a compiler, and it never covers
    another processor than the pinned node type, which is what makes the reference's byte comparison mean anything.
    On a platform where no bytes are compared (CPU_PINS_NOTHING) another processor model is no ground to refuse."""
    if key == REFERENCE and not fp["compared"].get("compiler"):
        return ("the compiler of the library could not be read, and a reference fingerprint without it would stop "
                "pinning the compiler (record from the build tree)")
    if key == REFERENCE and fp["compared"].get("cpu") != REFERENCE_CPU:
        return (f"the reference platform is pinned to one node type, {REFERENCE_CPU!r}, and this host is "
                f"{fp['compared'].get('cpu')!r}: run on a node of the pinned type (the batch script of the gate asks "
                "for one), or change REFERENCE_CPU in a commit that argues the new pin and re-records")
    committed = G0 / "baseline" / key / "fingerprint.json"
    if not committed.is_file():
        if key == REFERENCE and not repin:
            return "no reference platform is recorded; pinning one is a separate, argued commit (--repin)"
        return ""
    mism = fingerprint_mismatch(json.loads(committed.read_text()), fp)
    if key in CPU_PINS_NOTHING:
        mism = [m for m in mism if not m.startswith("cpu: ")]
    if not mism or repin:
        return ""
    return (f"this host has the platform key {key!r} but not the fingerprint recorded for it ({'; '.join(mism)}). "
            "To measure the tier-C spread of another host, give it a name of its own (AXMP_G0_PLATFORM=<name>); to "
            "re-record a platform that moved, which is a separate, argued commit, pass --repin")


def mask_keys(masks: dict) -> set:
    return ({("A", m["entry"], m["op"], m["stream"]) for m in masks.get("tier_a", [])}
            | {("B", m["entry"], m["file"], m["pointer"]) for m in masks.get("tier_b", [])}
            | {("C", m["entry"]) for m in masks.get("tier_c_by_name", [])})


def new_masks(measured: dict, committed: dict | None) -> list[tuple]:
    """The masks that the reproducibility measurement found and the committed list does not have. The lists only shrink
    (docs/developer/g0.md), so a mask that is new is a difference to look into, not something `record` may write."""
    return sorted(mask_keys(measured) - mask_keys(committed or {}))


def refuse_new_masks(masks: dict, key: str, args) -> bool:
    committed = G0 / "baseline" / key / "masks.json"
    added = new_masks(masks, json.loads(committed.read_text()) if committed.is_file() else None)
    if not added or args.allow_new_masks:
        return False
    print("g0: the reproducibility measurement found masks that the committed list for this platform does not have; "
          "the mask lists only shrink, so this is a difference to explain, not to record:")
    for k in added:
        print("  " + " ".join(map(str, k)))
    print("(a first baseline of a platform or of a new manifest entry, or a reviewed addition, is recorded with "
          "--allow-new-masks)")
    return True


def _mk(p: Path) -> Path:
    p.mkdir(parents=True, exist_ok=True)
    return p


def _figures_of(runs: dict, masks: dict, more_patterns: dict | None = None) -> dict:
    """The figures, the non-numeric leaves and the layout of results.json of each run, without the leaves masked for
    the entry (`more_patterns`: the timing leaves of an entry that has no tier-B record, hence no masks)."""
    pats = {k: list(v) for k, v in (more_patterns or {}).items()}
    for m in masks["tier_b"]:
        if m["file"] == "results.json":
            pats.setdefault(m["entry"], []).append(m["pointer"])
    ident = identity_patterns("results.json")
    docs = {k: o["files"]["results.json"]["doc"] for k, o in runs.items() if "results.json" in o["files"]}
    return {"figures": {k: figures(d, pats.get(k, []) + ident) for k, d in docs.items()},
            "discrete": {k: discrete(d, pats.get(k, []) + ident) for k, d in docs.items()},
            "layout": {k: layout(d) for k, d in docs.items()}}


def _patterns(masks: dict, entry_id: str) -> dict:
    pats = {}
    for m in masks["tier_b"]:
        if m["entry"] == entry_id:
            pats.setdefault(m["file"], []).append(m["pointer"])
    return pats


def figure_record(key: str) -> dict | None:
    """The figures, the non-numeric leaves and the layout recorded on a platform: in `spread/<key>.json`, or, for a
    platform that once was the reference platform, in `baseline/<key>/figures.json`. It is the same measurement under
    another file name, so a change of reference platform moves no recorded number from one file to another."""
    return _read(G0 / "spread" / f"{key}.json") or _read(G0 / "baseline" / key / "figures.json")


def reference_figures() -> dict:
    """What tier C compares with: the reference platform's figures, non-numeric leaves and layout."""
    return _read(G0 / "baseline" / REFERENCE / "figures.json") or {"figures": {}, "discrete": {}, "layout": {}}


def ambiguous_figure_records() -> list[str]:
    """Platforms whose figures are recorded in two places at once: `spread/<key>.json` and `baseline/<key>/figures.json`.
    One of the two is left over from an earlier role of the platform and only one is read, so the superseded file is
    removed rather than left to be read as the current measurement. The reference platform must have no spread file at
    all, because it is not a spread against itself."""
    both = {p.stem for p in (G0 / "spread").glob("*.json") if (G0 / "baseline" / p.stem / "figures.json").is_file()}
    if (G0 / "spread" / f"{REFERENCE}.json").is_file():
        both.add(REFERENCE)
    return sorted(both)


def measured_platforms() -> dict:
    """{platform: its figure record} for every platform but the reference: the measurements the tier-C tolerances are
    derived from. The reference's own record is not a spread (it is the value everything is compared with)."""
    keys = {p.stem for p in (G0 / "spread").glob("*.json")}
    keys |= {p.parent.name for p in (G0 / "baseline").glob("*/figures.json")}
    out = {}
    for key in sorted(keys - {REFERENCE}):
        rec = figure_record(key)
        if rec:
            out[key] = rec
    return out


def own_record(key: str, fp: dict) -> tuple[dict | None, list[str]]:
    """This host's own tier-B record ({"entries", "masks", "by_name", "leaves"}), or None and why there is none to
    compare with: no record under its platform key, a record of an older harness, or another fingerprint."""
    base = G0 / "baseline" / key
    rec_fp, tier_b, masks = _read(base / "fingerprint.json"), _read(base / "tierB.json"), _read(base / "masks.json")
    if rec_fp is None or tier_b is None or masks is None:
        return None, [f"no tier-B record for platform {key!r}"]
    if tier_b.get("format") != FORMAT_B:
        return None, [f"the tier-B record of {key!r} has the format {tier_b.get('format')!r}, not {FORMAT_B!r}: it was made "
                      "by an older harness and must be recorded again"]
    mism = fingerprint_mismatch(rec_fp, fp)
    if mism:
        return None, mism
    figs = reference_figures() if key == REFERENCE else figure_record(key)
    return {"entries": tier_b["entries"], "masks": masks, "leaves": figs or {},
            "by_name": {m["entry"]: m["reason"] for m in masks["tier_c_by_name"]}}, []


def compared_as(key: str, on_reference: bool, require_reference: bool) -> tuple[str, str]:
    """The platform `check` compares this host as, and the note that says why it is not the one the key names.

    The platform key holds only the system, the machine and the build kind, so a node of the reference platform that
    was not given its name has the key of a hosted platform (`linux-x86_64-mpi`). Two things override the key:

    * the **fingerprint**: a host that has the reference's compared fields is the reference platform;
    * `--require-reference`, the host's **claim** to that role. It must not depend on the fingerprint matching, since
      the whole point of the flag is that a fingerprint which is not the reference's is a failure there, not a
      refusal of tier B. Without this, a reference node whose fingerprint had moved would fall back to its natural
      key, a hosted one, where tier B is no part of the gate -- and the flag would pass over the very case it exists
      for.
    """
    if key == REFERENCE:
        return key, ""
    if on_reference:
        return REFERENCE, (f"this host has the fingerprint recorded for the reference platform {REFERENCE!r} and is "
                           f"compared as the reference platform (name it so with AXMP_G0_PLATFORM={REFERENCE})")
    if require_reference:
        return REFERENCE, (f"--require-reference: this host claims the reference platform {REFERENCE!r} and is compared "
                           f"as it, under the key {key!r}; its fingerprint is not the recorded one, which is a failure "
                           f"of tier B here, not a refusal (name the platform with AXMP_G0_PLATFORM={REFERENCE})")
    return key, ""


def cmd_check(args) -> int:
    fp = fingerprint()
    ref_dir = G0 / "baseline" / REFERENCE
    ref_fp = _read(ref_dir / "fingerprint.json")
    on_reference = ref_fp is not None and not fingerprint_mismatch(ref_fp, fp)
    key, note = compared_as(fp["platform"], on_reference, args.require_reference)
    if note:
        print("note: " + note)
    base = G0 / "baseline" / (args.baseline_platform or key)
    if not (base / "tierA.json").is_file():
        print(f"g0: no baseline for platform {base.name!r} (recorded: {sorted(p.name for p in (G0 / 'baseline').iterdir())})")
        return 2
    manifest = load_manifest()
    names, bad = _only(args, manifest)
    if bad:
        print("g0: " + bad)
        return 2
    masks = json.loads((base / "masks.json").read_text())
    tiers = args.tiers.upper()
    diffs, notes = [], []
    numbers_failed = False
    n_compared = 0  # tier-A documents and manifest entries actually run and compared: none is not a pass
    refused = ""    # why tier B was refused here (not a failure, and not a full pass either)
    n_unchecked = 0  # figures of results.json that tier C ran over and compared with nothing
    here_pending = pending().get(key, {"tier_a": [], "tier_b": [], "reason": ""})
    tmp = Path(tempfile.mkdtemp(prefix="g0-"))
    try:
        if "A" in tiers:
            now = tier_a(_mk(tmp / "a"))
            base_a = json.loads((base / "tierA.json").read_text())
            # an entry the platform has no record of is reported as pending below, not as a difference; on the reference
            # platform pending is a failure, so nothing is passed over there
            no_record = set() if key == REFERENCE else set(here_pending["tier_a"])
            diffs += tier_a_diff(base_a, now, masks["tier_a"], where=f"tier A against the baseline of {base.name}",
                                 no_record=no_record)
            notes.append(f"tier A: {len(now['designs'])} designs and {len(now['corpus'])} corpus documents compared")
            n_compared += len(now["designs"]) + len(now["corpus"])
        want_b, want_c = "B" in tiers, "C" in tiers
        own, why_not = (None, [])
        if key in TIER_AC_PLATFORMS:
            # a hosted runner: its record was made while the hosted image was the reference platform, and the image
            # moves, so its bytes are not the gate's statement any more; its numbers are compared in tier C. `key` is
            # the reference's whenever this host has its fingerprint or claims its role (compared_as), so neither
            # lands here.
            if want_b:
                notes.append(f"tier B: not part of the gate on {key}: it is compared at tiers A and C, with its numbers "
                             "against the reference platform's record (docs/developer/g0.md)")
                want_b = False
        elif key in TIER_A_PLATFORMS:
            if want_b or want_c:
                notes.append(f"tiers B and C: not part of the gate on {key}: it is compared at tier A only, its text "
                             "against its own record (docs/developer/g0.md)")
            want_b = want_c = False
        else:
            if want_b or want_c:
                own, why_not = own_record(key, fp)
            if want_b and own is None:
                why = "this host cannot be compared with a record of its own: " + "; ".join(why_not)
                if args.require_reference:
                    # the reference platform is one pinned node type: a fingerprint that moved means the processor, the
                    # image, the compiler or the mesher changed and needs a separate, argued re-recording; tier B must
                    # not quietly turn into tier C there
                    diffs.append("tier B: " + why)
                else:
                    notes.append("tier B REFUSED: " + why)
                    refused = why
                    want_c = True
                want_b = False
        if want_c and on_reference:
            # said rather than passed over silently: on the reference platform tier C has nothing to compare with, and
            # tier B is the stronger statement about this host
            notes.append("tier C: not run on the reference platform: it compares the other platforms with this "
                         "platform's record, while tier B compares this host with it byte for byte")
        want_c = want_c and not on_reference
        if want_b or want_c:
            entries = _entries(manifest["tier_b"], names)
            if names and not entries:
                diffs.append(f"--only {args.only}: this build runs none of these entries (they need the 3D engine), so "
                             "nothing would be compared")
            ref_b = (_read(ref_dir / "tierB.json") or {}).get("entries", {})
            ref_masks = json.loads((ref_dir / "masks.json").read_text())
            ref_c = reference_figures()
            tol = tolerances_for(key)
            allowed_new = manifest.get("allowed_new_files", [])
            for e in entries:
                eid = e["id"]
                obs = run_entry(e, _mk(tmp / "b" / eid))
                before = len(diffs)
                n_compared += 1
                diffs += ["tier B/C: " + d for d in identity_diffs(eid, obs)]
                if want_b:
                    if eid in own["entries"]:
                        diffs += tier_b_compare(eid, own["entries"][eid], obs, _patterns(own["masks"], eid), allowed_new,
                                                {k: own["leaves"].get(k, {}).get(eid, {}) for k in ("figures", "discrete")})
                        notes.append(f"tier B: {eid} compared with this platform's record")
                    elif eid in own["by_name"] and key != REFERENCE:
                        # a host of its own: tier C still compares the entry with the reference platform's record
                        notes.append(f"tier B: {eid} NOT compared here: {own['by_name'][eid]}; tier C compares it with "
                                     "the reference platform's record")
                    elif eid in own["by_name"]:
                        # on the reference platform nothing else compares it: tier C does not run here, so an entry
                        # whose bytes are not reproducible on the pinned node type is compared by nothing
                        diffs.append(f"tier B: {eid}: the reference platform's record lists it as not reproducible there "
                                     f"({own['by_name'][eid]}), and tier C does not run on the reference platform, so "
                                     "nothing compares the entry: make it reproducible, or take it off the manifest "
                                     "(docs/developer/g0.md)")
                    else:
                        diffs.append(f"tier B: {eid}: this platform has no record of the entry (it is pending: "
                                     "docs/developer/g0.md, tests/g0/pending.json)")
                if want_c:
                    mesh_only = e.get("op") == "mesh"
                    in_ref = eid in ref_b if mesh_only else (eid in ref_c["figures"] and eid in ref_c.get("discrete", {}))
                    # a solve needs a tolerance per figure, which is measured; a mesh entry needs none, because tier C
                    # asks only that it still succeeds with the reference's exit status
                    measured_here = mesh_only or eid in tol["entries"]
                    if not in_ref:
                        # a host of its own may go on with its own record alone; on a recorded platform a manifest entry
                        # without a reference record is a failure
                        if key not in RECORDED_PLATFORMS and own is not None and eid in own["entries"] and want_b:
                            notes.append(f"tier C: {eid} PENDING: the reference platform has no record of it yet; compared "
                                         "with this host's own record only")
                        else:
                            diffs.append(f"tier C: {eid}: the reference platform has no record of the entry (it is "
                                         "pending: docs/developer/g0.md, tests/g0/pending.json)")
                    else:
                        ref_status = ref_b[eid]["status"] if eid in ref_b else 0
                        if ref_status != obs["status"]:
                            diffs.append(f"tier C: {eid}: exit status {ref_status} -> {obs['status']}")
                        if mesh_only:  # a mesh has no figures; tier C asks only that it still succeeds
                            notes.append(f"tier C: {eid} (mesh: exit status only)")
                        elif not measured_here:
                            # nothing was measured here that could set the tolerances of this entry's figures, so they
                            # are not compared: the entry is pending on this platform (listed, with the reason, in
                            # tests/g0/pending.json) and the reference platform covers it at tier B. The entry was run
                            # and its exit status compared, so a design that stopped solving here still fails.
                            notes.append(f"tier C: {eid} PENDING on {key}: no spread of this entry was measured here, so "
                                         "its figures have no tolerance; its exit status is compared "
                                         "(tests/g0/pending.json)")
                        else:
                            pats = _patterns(ref_masks, eid).get("results.json", [])
                            d, n_asserted, n_left, n_unmeasured = tier_c_compare(
                                eid, ref_c["figures"][eid], obs, pats, tol["tolerances"].get(eid, {}),
                                set(tol["unasserted"].get(eid, {})))
                            diffs += d
                            n_unchecked += n_left + n_unmeasured
                            n_exact = 0
                            if "results.json" in obs["files"]:
                                d, n_exact = tier_c_exact(eid, ref_c["discrete"][eid], ref_c["layout"][eid],
                                                          obs["files"]["results.json"]["doc"], pats,
                                                          tol["unasserted_discrete"].get(eid, {}), tol["unasserted_layout"].get(eid, []))
                                diffs += d
                            notes.append(f"tier C: {eid} compared with the reference platform's record ({n_asserted} figures "
                                         f"asserted, {len(tol['over_ceiling'].get(eid, {}))} of them over the round-off ceiling "
                                         f"{SPREAD_CEILING:g} at ten times their spread; {n_left} not: mesh-sized or spread over "
                                         f"{WIDE_SPREAD_CEILING:.3g}; {n_unmeasured} not: no spread of them was measured here, so "
                                         f"they have no tolerance; {n_exact} non-numeric leaves and the layout compared exactly, "
                                         f"{len(tol['unasserted_discrete'].get(eid, {}))} leaves and "
                                         f"{len(tol['unasserted_layout'].get(eid, []))} layout pointers listed as differing here)")
                numbers_failed = numbers_failed or len(diffs) > before
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    for n in notes:
        print(n)
    for d in diffs:
        print("FAIL " + d)
    if numbers_failed:
        print("this host and the fingerprint recorded for its platform (a platform that moved, or the code?):")
        for line in fingerprint_report(_read(G0 / "baseline" / key / "fingerprint.json"), fp):
            print("  " + line)
    n_pending = len(here_pending["tier_a"]) + len(here_pending["tier_b"])
    if n_pending:
        what = (f"{len(here_pending['tier_a'])} tier-A and {len(here_pending['tier_b'])} tier-B/C entries of the "
                f"manifest have no record on {key} (tests/g0/pending.json)")
        if key == REFERENCE:
            # whatever was run and compared: the gate does not pass on the reference platform while it lacks a record
            # of something, because nothing else compares those entries byte for byte
            diffs.append("pending")
            print(f"FAIL pending on the reference platform: {what}; record them (docs/developer/g0.md)")
        else:
            # not a pass of anything, and not silent: the entries are named here and in tests/g0/pending.json, with the
            # reason, and the reference platform covers them at tier B
            print(f"PENDING on {key}: {what}: {here_pending['reason']}")
            for i in here_pending["tier_a"] + here_pending["tier_b"]:
                print(f"  pending {i}")
    if not diffs and n_compared == 0:
        # e.g. `--tiers C` on the reference platform, or `--tiers B` on a platform compared at tiers A and C: the notes
        # above say why the tier does not run here, and that is not a verdict on anything
        print(f"G0: nothing compared here (tiers {tiers!r} on {key}): not a pass")
        return 2
    if refused:
        # Not a failure: the host is not the reference platform, and a fingerprint that moved is no change in the code.
        # But the run asserted far less than one with tier B, and its last line must not read like the same pass.
        print(f"G0 ran WITHOUT TIER B on {key}: {refused}. No byte was compared. "
              + (f"Tier C alone compared the solves, and compared {n_unchecked} figures of their results.json with "
                 "nothing: those tests/g0/tolerances.json lists as unasserted for this platform, the mesh-sized ones and "
                 "those without a measured spread here. Nor does tier C see a change below a figure's tolerance, an "
                 "array of more than 64 numbers, or any other file of a run (the meshes, scene.json, the status file, "
                 "stdout)" if want_c else "Tier C does not run here either, so no number was compared")
              + ". Record the platform again to get tier B back (docs/developer/g0.md)")
    print("G0: " + ("FAILED" if diffs else "passed WITHOUT TIER B (refused: see above)" if refused else "passed")
          + (f" ({n_pending} entries pending on {key})" if n_pending else ""))
    return 1 if diffs else 0


REASON_REFERENCE = ("the reference platform compares these byte for byte; `check --require-reference` fails while one of "
                    "them has no record there, so the gate cannot pass until it is recorded on a node of the pinned "
                    "type. An entry the record lists as not reproducible there (`tier_c_by_name`) is in this list too: "
                    "tier C does not run on the reference platform, so nothing would compare it")
REASON_TIER_AC = ("this platform's record is the one its hosted runner made while that image was the reference platform; "
                  "development CI does not run there, so the entries added since are recorded again only by the public "
                  "repository's CI at a release (.github/workflows/g0.yml, `record`). Until then they are compared on the "
                  "reference platform alone, at tiers A and B, and `check` says PENDING for them here")


def recorded_entries(key: str) -> dict:
    """What the committed baseline of a platform holds: the ids of its tier-A designs and corpus documents, and of the
    manifest entries it can be compared on. On the reference platform that means a tier-B record under the present
    harness, and, for a solve, the figures tier C reads; an entry the record lists as not reproducible there
    (`tier_c_by_name`) is **not** one of them, because tier C does not run on the reference platform and nothing else
    compares it. On a platform compared at tiers A and C it means a measurement of its own that gives the entry's
    figures a tolerance; a mesh entry needs none, because tier C compares its exit status alone."""
    base = G0 / "baseline" / key
    a = _read(base / "tierA.json") or {}
    manifest = load_manifest()
    meshes = {e["id"] for e in manifest["tier_b"] if e.get("op", "solve") == "mesh"}
    if key == REFERENCE:
        b = _read(base / "tierB.json") or {}
        tier_b = set(b.get("entries", {})) if b.get("format") == FORMAT_B else set()
        figs = reference_figures()  # the reference's record of a solve is also what tier C reads: its figures
        has_figures = set(figs.get("figures", {})) & set(figs.get("discrete", {}))
        tier_b = {i for i in tier_b if i in meshes or i in has_figures}
    else:
        tier_b = set(tolerances_for(key)["entries"]) | meshes
    return {"designs": set(a.get("designs", {})), "corpus": set(a.get("corpus", {})), "tier_b": tier_b}


def pending() -> dict:
    """{recorded platform: {"role", "reason", "tier_a": [...], "tier_b": [...]}}: the entries of the manifest and of the
    corpus that the committed records give that platform no comparison for. On the reference platform `check` fails for
    each of them; on a platform compared at tiers A and C it prints PENDING and names them, and the reference platform
    is what compares them (docs/developer/g0.md)."""
    manifest = load_manifest()
    out = {}
    for key in RECORDED_PLATFORMS:
        have = recorded_entries(key)
        mpi = key.endswith("-mpi")
        out[key] = {
            "role": "reference (tiers A and B)" if key == REFERENCE else "tiers A and C",
            "reason": REASON_REFERENCE if key == REFERENCE else REASON_TIER_AC,
            "tier_a": [d["id"] for d in manifest["tier_a"]["designs"] if d["id"] not in have["designs"]]
                      + [f"corpus:{d['id']}" for d in load_corpus() if d["id"] not in have["corpus"]],
            "tier_b": [e["id"] for e in manifest["tier_b"]
                       if (mpi or not e.get("requires_engine_3d")) and e["id"] not in have["tier_b"]]}
    return out


def pending_document() -> dict:
    return {"format": FORMAT,
            "what": ("generated by `g0.py pending --write`, never edited: per recorded platform, the manifest and corpus "
                     "entries the committed records give it no comparison for, with the role of the platform and the "
                     "reason. `g0.py check` fails for each of them on the reference platform and prints PENDING for each "
                     "of them elsewhere"),
            "platforms": pending()}


def cmd_pending(args) -> int:
    doc = pending_document()
    if args.write:
        _write(G0 / "pending.json", doc)
    for key, p in doc["platforms"].items():
        print(f"{key} ({p['role']}): {len(p['tier_a'])} tier-A and {len(p['tier_b'])} tier-B/C entries without a record")
        for kind in ("tier_a", "tier_b"):
            for i in p[kind]:
                print(f"  {kind} {i}")
    return 0


def tolerances_for(platform_key_: str) -> dict:
    """The tier-C tolerances and lists of this platform: those measured on it (its family is its platform key, the one
    its figure record was recorded under), or `any`, the worst case over every measured platform, for one not measured.
    `tolerances` holds both classes of asserted figures, the round-off class and the one over the ceiling; `entries` are
    the manifest entries the family covers, which is what tier C can compare there."""
    f = G0 / "tolerances.json"
    if not f.is_file():
        return {"floor": TOL_FLOOR, "tolerances": {}, "over_ceiling": {}, "unasserted": {}, "unasserted_discrete": {},
                "unasserted_layout": {}, "entries": set()}
    doc = json.loads(f.read_text())
    fam = doc["families"].get(platform_key_) or doc["families"]["any"]
    over = fam.get("over_ceiling", {})
    tols = {e: dict(m) for e, m in fam["tolerances"].items()}
    for entry, m in over.items():
        tols.setdefault(entry, {}).update({ptr: v[0] for ptr, v in m.items()})
    return {"floor": doc["floor"], "tolerances": tols, "over_ceiling": over, "unasserted": fam["unasserted"],
            "unasserted_discrete": fam.get("unasserted_discrete", {}), "unasserted_layout": fam.get("unasserted_layout", {}),
            "entries": set(fam["tolerances"])}


def derive_tolerances(ref: dict, spreads: dict) -> dict:
    """The document of tests/g0/tolerances.json from the reference platform's record (`ref`: figures, discrete, layout)
    and the spread records by platform. One family per measured platform, so that a noisy host loosens only its own
    comparison, and `any`, the worst case over all of them, for a platform that was not measured. An entry that the
    reference has no record of yet gives nothing. An entry that is not reproducible on a platform has both of its runs
    in that platform's record (`second_run`), and its spread is the larger of the two."""
    fams = {plat: [plat] for plat in sorted(spreads)}
    fams["any"] = sorted(spreads)
    out, summary = {}, {}
    for fam, plats in sorted(fams.items()):
        spread, un_discrete, un_layout = {}, {}, {}
        for plat in plats:
            # an entry that is not reproducible on the platform has two runs on record: its spread spans both
            for rec in [spreads[plat]] + ([spreads[plat]["second_run"]] if "second_run" in spreads[plat] else []):
                for entry, figs in rec["figures"].items():
                    if entry not in ref["figures"]:
                        continue
                    for ptr, v in figs.items():
                        if ptr in ref["figures"][entry] and not mesh_sized(ptr):
                            d = rel_diff(ref["figures"][entry][ptr], v)
                            cur = spread.setdefault(entry, {}).setdefault(ptr, [0.0, ""])
                            if d > cur[0]:
                                cur[0], cur[1] = d, plat
                    found = discrete_difference(_no_identity(ref["discrete"][entry]), _no_identity(rec["discrete"][entry]))
                    for ptr, (a, b) in found.items():
                        un_discrete.setdefault(entry, {}).setdefault(ptr, [a, {}])[1][plat] = b
                    moved = layout_difference(ref["layout"][entry], rec["layout"][entry])
                    if moved:
                        un_layout[entry] = sorted(set(un_layout.get(entry, [])) | set(moved))
        tols, over, unasserted, summ = {}, {}, {}, {}
        for entry, m in spread.items():
            tols[entry] = {p: max(TOL_FACTOR * d, TOL_FLOOR) for p, (d, _) in m.items() if d <= SPREAD_CEILING}
            over[entry] = {p: [TOL_FACTOR * d, d, plat] for p, (d, plat) in sorted(m.items())
                           if SPREAD_CEILING < d < WIDE_SPREAD_CEILING}
            unasserted[entry] = {p: [d, plat] for p, (d, plat) in sorted(m.items())
                                 if d > SPREAD_CEILING and p not in over[entry]}
            n_all = sum(1 for p in ref["figures"][entry])
            n_mesh = sum(1 for p in ref["figures"][entry] if mesh_sized(p))
            n_disc = len(_no_identity(ref["discrete"][entry]))
            summ[entry] = {"figures": n_all, "mesh_sized": n_mesh, "asserted": len(tols[entry]),
                           "asserted_over_ceiling": len(over[entry]),
                           "unasserted": len(unasserted[entry]),
                           "largest_asserted_tolerance": max(tols[entry].values(), default=0.0),
                           "largest_tolerance_over_ceiling": max((v[0] for v in over[entry].values()), default=0.0),
                           "non_numeric": n_disc,
                           "non_numeric_asserted": n_disc - len(set(un_discrete.get(entry, {})) & set(ref["discrete"][entry])),
                           "non_numeric_unasserted": len(un_discrete.get(entry, {})),
                           "layout_pointers_unasserted": len(un_layout.get(entry, []))}
        out[fam] = {"measured_on": plats, "tolerances": tols, "over_ceiling": over, "unasserted": unasserted,
                    "unasserted_discrete": un_discrete, "unasserted_layout": un_layout}
        summary[fam] = summ
    return {
        "format": FORMAT,
        "rule": (f"per measured platform (and `any`: all of them), relative to the reference platform's value alone. "
                 f"`tolerances`, the round-off class: max({TOL_FACTOR:g} x the largest relative spread of the quantity, "
                 f"{TOL_FLOOR:g}), for a spread up to {SPREAD_CEILING:g}. `over_ceiling`, the class of a quantity that "
                 f"spreads more because the problem solved differs: [{TOL_FACTOR:g} x its spread, the spread, the platform], "
                 f"for a spread below {WIDE_TOLERANCE_LIMIT:g} / ({TOL_FACTOR:g} + 0.5), so that the platform's own value, "
                 f"halved or doubled, is outside the tolerance. `unasserted`: a quantity that spreads more than that, with its "
                 f"spread and platform. Mesh-sized quantities are not asserted. A leaf that is not a number, and the "
                 f"layout, are compared exactly, except those listed as unasserted_discrete (with the reference's value "
                 f"and each platform's) and unasserted_layout because they were measured to differ"),
        "floor": TOL_FLOOR, "spread_ceiling": SPREAD_CEILING, "wide_spread_ceiling": WIDE_SPREAD_CEILING,
        "wide_tolerance_limit": WIDE_TOLERANCE_LIMIT, "mesh_sized": MESH_SIZED.pattern,
        "summary": summary, "families": out}


def _asserted(fam: dict) -> dict:
    """{entry: {pointer: tolerance}} over both classes of a family of a tolerances document."""
    out = {e: dict(m) for e, m in fam["tolerances"].items()}
    for entry, m in fam.get("over_ceiling", {}).items():
        out.setdefault(entry, {}).update({ptr: v[0] for ptr, v in m.items()})
    return out


def loosened(old: dict, new: dict) -> list[str]:
    """What `new` (a tolerances document) asserts less strictly than `old`, family by family: a family or an entry that
    is gone, a figure that is no longer asserted, a tolerance that grew (a figure that moved from the round-off class
    to the one over the ceiling included), a non-numeric leaf or a layout pointer newly listed as differing. A family
    that only `new` has is a new measurement and loosens nothing."""
    out = []
    for fam, o in sorted(old.get("families", {}).items()):
        n = new["families"].get(fam)
        if n is None:
            out.append(f"{fam}: the family is gone")
            continue
        na = _asserted(n)
        for entry, tols in sorted(_asserted(o).items()):
            nt = na.get(entry, {})
            for ptr, t in sorted(tols.items()):
                if ptr not in nt:
                    out.append(f"{fam}: {entry}: {ptr} is no longer asserted")
                elif nt[ptr] > t * (1 + 1e-12):
                    out.append(f"{fam}: {entry}: {ptr}: tolerance {t:.3g} -> {nt[ptr]:.3g}")
        for kind in ("unasserted_discrete", "unasserted_layout"):
            if kind not in o:  # a record made before the non-numeric leaves were compared: nothing to compare with
                continue
            for entry, lst in sorted(n.get(kind, {}).items()):
                for ptr in sorted(set(lst) - set(o[kind].get(entry, []))):
                    out.append(f"{fam}: {entry}: {ptr} is newly listed in {kind}")
    return out


def cmd_tolerances(args) -> int:
    """Derive tests/g0/tolerances.json from the recorded spread (derive_tolerances). Like a mask list, the file only
    tightens: a derivation that asserts less than the committed file stops, unless --allow-loosening is given for a
    reviewed, argued change."""
    both = ambiguous_figure_records()
    if both:
        print("g0: the figures of these platforms are recorded in two places at once, and only one of the two is read; "
              "remove the superseded file (the reference platform keeps `baseline/<key>/figures.json` and has no spread "
              f"file; every other platform keeps `spread/<key>.json`): {', '.join(both)}")
        return 2
    ref = reference_figures()
    spreads = {}
    for key, s in measured_platforms().items():
        if "discrete" not in s:
            print(f"g0: the figure record of {key} was made before the non-numeric leaves were; record it again or "
                  "remove it")
            return 2
        spreads[key] = s
    doc = derive_tolerances(ref, spreads)
    target = G0 / "tolerances.json"
    if target.is_file() and not args.allow_loosening:
        worse = loosened(json.loads(target.read_text()), doc)
        if worse:
            print(f"g0: the spread now recorded would loosen the committed tolerances in {len(worse)} places; a tolerance "
                  "is never loosened without an argued reason (--allow-loosening for a reviewed change):")
            for w in worse[:40]:
                print("  " + w)
            return 3
    _write(target, doc)
    for fam in sorted(doc["summary"]):
        keys = ("figures", "mesh_sized", "asserted", "asserted_over_ceiling", "unasserted", "non_numeric",
                "non_numeric_unasserted", "layout_pointers_unasserted")
        tot = {k: sum(v[k] for v in doc["summary"][fam].values()) for k in keys}
        print(f"{fam}: platforms {doc['families'][fam]['measured_on']}: {tot}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
