REFERENCE_CPU = "Intel(R) Xeon(R) Gold 6330 CPU @ 2.00GHz"
# The platforms of the GitHub-hosted runners. Their records are those of the CI runs made while the hosted image was
# the reference; development CI no longer runs there (`.github/workflows/g0.yml` serves the public repository's CI at a
# release). They are compared at tier A, against their own committed text record, and at tier C, against the reference
