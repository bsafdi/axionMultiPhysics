def _import_package():
    sys.path.insert(0, str(ROOT / "python"))
    import axionmultiphysics as axmp  # noqa: E402

    return axmp


def find_axmp() -> str | None:
    """The axmp executable: AXMP_BIN (or AXMP_EXE, which the package reads), the package's own search, then the build
    directories that docs/developer/g0.md names."""
    for var in ("AXMP_BIN", "AXMP_EXE"):
        if os.environ.get(var):
            return os.environ[var]
    _import_package()
    from axionmultiphysics import _paths

    exe = _paths.axmp_path()
    if exe:
        return exe
    for d in ("build-mpi", "build"):
        if (ROOT / d / "axmp").is_file():
            return str(ROOT / d / "axmp")
    return None


def axmp_exe() -> str:
    exe = find_axmp()
    if exe is None:
        raise SystemExit("g0: the axmp executable was not found (build it, or set AXMP_BIN)")
    return exe


def mesher_exe() -> str | None:
    if os.environ.get("AXMP_MESHER"):
        return os.environ["AXMP_MESHER"]
    _import_package()
    from axionmultiphysics import _paths

    exe = _paths.mesher_path()
    if exe:
        return exe
    for d in ("build-mpi", "build"):
        if (ROOT / d / "axmp-mesher").is_file():
            return str(ROOT / d / "axmp-mesher")
    return None


def launcher() -> list[str]:
    """Words put in front of `axmp` for solves (AXMP_G0_LAUNCH, e.g. "mpirun -n 1"); none by default."""
    return os.environ.get("AXMP_G0_LAUNCH", "").split()


def launched_ranks() -> int:
    """The rank count the launcher asks for (its -n / -np / --np argument); one without a launcher."""
    words = launcher()
    for i, w in enumerate(words[:-1]):
        if w in ("-n", "-np", "--np", "--n") and words[i + 1].isdigit():
            return int(words[i + 1])
    return 1


def _run(cmd, cwd=None, env=None, timeout=1800):
    e = {k: v for k, v in os.environ.items() if k not in ENV_CLEARED}
    e.update(fixed_environment())
    if env:
        e.update(env)
    try:
        p = subprocess.run(cmd, cwd=cwd or ROOT, env=e, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"status": "timeout", "stdout": "", "stderr": ""}
    return {"status": p.returncode, "stdout": p.stdout, "stderr": p.stderr}


def build_kind() -> str:
    info = _import_package().build_info()
    return "mpi" if info.get("engine_3d") else "sequential"


def platform_key() -> str:
    if os.environ.get("AXMP_G0_PLATFORM"):
        return os.environ["AXMP_G0_PLATFORM"]
    system = {"Linux": "linux", "Darwin": "macos"}.get(platform.system(), platform.system().lower())
    machine = platform.machine().lower()
    machine = {"amd64": "x86_64", "aarch64": "arm64" if system == "macos" else "aarch64"}.get(machine, machine)
    return f"{system}-{machine}-{build_kind()}"


def _os_release() -> dict:
    out = {}
    try:
        for line in Path("/etc/os-release").read_text().splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                out[k] = v.strip('"')
    except OSError:
        pass
    return out


def compiler_of_library(info: dict) -> str:
    """The compiler that built libaxionmultiphysics: the ident string compiled into its binary."""
    d = (info.get("library") or {}).get("build_dir") or info.get("build_dir") or ""
    for lib in sorted(Path(d).glob("libaxionmultiphysics*")) if d else []:
        if lib.is_file() and not lib.suffix == ".a":
            m = re.search(rb"(GCC: \([^\x00]*\)[^\x00]*|(?:Apple )?clang version [^\x00\n]*)", lib.read_bytes())
            if m:
                return m.group(1).decode("utf-8", "replace")
    # a binary format that carries no ident string (Mach-O): what the build system recorded of its compiler
    for f in sorted(Path(d).glob("CMakeFiles/*/CMakeCXXCompiler.cmake")) if d else []:
        text = f.read_text("utf-8", "replace")
        cid = re.search(r'set\(CMAKE_CXX_COMPILER_ID "([^"]*)"\)', text)
        ver = re.search(r'set\(CMAKE_CXX_COMPILER_VERSION "([^"]*)"\)', text)
        if cid and ver:
            return f"{cid.group(1)} {ver.group(1)}"
    return ""


def cpu_model() -> str:
    try:
        if platform.system() == "Darwin":
            return subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return ""


def _linked_libraries(binary: str) -> dict:
    """{name: path} of the shared libraries a binary loads (ldd; otool -L on macOS)."""
    try:
        if platform.system() == "Darwin":
            out = subprocess.run(["otool", "-L", binary], capture_output=True, text=True).stdout
            return {Path(line.split()[0]).name: line.split()[0] for line in out.splitlines()[1:] if line.strip()}
        out = subprocess.run(["ldd", binary], capture_output=True, text=True).stdout
    except OSError:
        return {}
    return {m.group(1): m.group(2) for m in re.finditer(r"^\s*(\S+) => (/\S+)", out, re.M)}


BLAS_NAME = re.compile(r"blas|lapack|mkl|atlas|blis|accelerate|veclib", re.I)
_OPENBLAS_PROBE = """
import ctypes, json, sys
lib, out = ctypes.CDLL(sys.argv[1]), {}
for fn, key in (("openblas_get_config", "config"), ("openblas_get_corename", "kernel")):
    try:
        f = getattr(lib, fn)
        f.restype = ctypes.c_char_p
        out[key] = f().decode()
    except Exception:
        pass
print(json.dumps(out))
"""


def _package_of(path: str) -> str:
    """The distribution package that owns a file and its version (Debian and Ubuntu; empty elsewhere)."""
    try:
        owner = subprocess.run(["dpkg", "-S", path], capture_output=True, text=True)
        if owner.returncode != 0:
            return ""
        pkg = owner.stdout.split(": ", 1)[0].split(",")[0].strip()
        ver = subprocess.run(["dpkg-query", "-W", "-f=${Version}", pkg], capture_output=True, text=True).stdout.strip()
        return f"{pkg} {ver}".strip()
    except OSError:
        return ""


def blas_libraries(info: dict) -> list[dict]:
    """The BLAS and LAPACK libraries the engine, `axmp` and the mesher load: the name they are loaded by, the file it
    resolves to (which carries the version where the library puts it there), the distribution package, and for an
    OpenBLAS its own configuration string and the kernel it runs with in the harness's environment."""
    d = (info.get("library") or {}).get("build_dir") or info.get("build_dir") or ""
    binaries = [str(f) for f in sorted(Path(d).glob("libaxionmultiphysics*")) if f.is_file() and f.suffix != ".a"] if d else []
    binaries += [b for b in (find_axmp(), mesher_exe()) if b]
    found = {}
    for b in binaries:
        for name, path in _linked_libraries(b).items():
            if BLAS_NAME.search(name):
                found[os.path.realpath(path)] = name
    out = []
    for real, name in sorted(found.items(), key=lambda kv: (kv[1], kv[0])):
        rec = {"name": name, "file": Path(real).name}
        if "openblas" in name.lower():
            probe = _run([sys.executable, "-c", _OPENBLAS_PROBE, real], timeout=60)
            try:
                rec.update(json.loads(probe["stdout"] or "{}"))
            except ValueError:
                pass
        pkg = _package_of(real)
        if pkg:
            rec["package"] = pkg
        out.append(rec)
    return out


def gmsh_version() -> str:
    """The gmsh the mesher links, as the mesher reports it in the info file of a small mesh."""
    with tempfile.TemporaryDirectory(prefix="g0-fp-") as t:
        exe = axmp_exe()
        d = Path(t) / "toroid.json"
        d.write_text(_run([exe, "template", "toroid"])["stdout"])
        _run([exe, "mesh", str(d), "-o", str(Path(t) / "m")], timeout=300)
        try:
            return str(json.loads((Path(t) / "m" / "mesh_info.json").read_text()).get("gmsh_version", ""))
        except (OSError, ValueError):
            return ""


def fingerprint() -> dict:
    """What the platform is. `compared` fields must all agree for a tier-B comparison; the rest is information, printed
    with its differences from the record when tier B or C fails. The thread count and the BLAS kernel are not compared
    fields: every run of the harness is given them (fixed_environment), so they cannot differ between two
    fingerprints. The **processor is compared**: the reference platform is one pinned node type of the development
    cluster, and an OpenBLAS or a compiler-generated code path that depends on the processor would otherwise move its
    bytes (the kernel is pinned on top of that, see BLAS_KERNEL_X86_64). Where no record of bytes is compared it is
    recorded and pins nothing (CPU_PINS_NOTHING, refuse_record). The BLAS library is information: which build of
    the package the host has is told by the record, not required by it."""
    axmp = _import_package()
    info = axmp.build_info()
    system = {"Darwin": "macos"}.get(platform.system(), platform.system().lower())
    if system == "linux":
        rel = _os_release()
        osid = f"{rel.get('ID', 'linux')}-{rel.get('VERSION_ID', '')}"
        libc = "-".join(platform.libc_ver())
    else:
        osid = f"macos-{platform.mac_ver()[0]}"
        libc = ""
    gmsh = gmsh_version()
    pins = ROOT / "third_party" / "SHA256SUMS.txt"
    compared = {
        "system": system,
        "machine": platform.machine().lower(),
        "os": osid,
        "libc": libc,
        "build": build_kind(),
        "compiler": compiler_of_library(info),
        "mesher": gmsh,
        "dependency_pins": dependency_pins_digest(pins) if pins.is_file() else "",
        "ranks": launched_ranks(),
        "strumpack": bool(info.get("strumpack", False)),
        "cpu": cpu_model(),
    }
    informational = {
        "ci": bool(os.environ.get("GITHUB_ACTIONS")),
        "environment_forced": fixed_environment(),
        "environment_cleared": list(ENV_CLEARED),
        "blas": blas_libraries(info),
        "runner_image": os.environ.get("ImageVersion", ""),
        "python": platform.python_version(),
        "build_info": _without_paths(info),
    }
    return {"format": FORMAT, "platform": platform_key(), "compared": compared, "informational": informational}


def _without_paths(info: dict) -> dict:
    """The build information without what names a directory of the machine it was built on."""
    return {k: (_without_paths(v) if isinstance(v, dict) else v) for k, v in info.items()
            if k not in ("git_dirty_files", "build_dir")}


def fingerprint_mismatch(base: dict, here: dict) -> list[str]:
    a, b = base["compared"], here["compared"]
    return [f"{k}: baseline {a.get(k)!r}, here {b.get(k)!r}" for k in sorted(set(a) | set(b)) if a.get(k) != b.get(k)]


def fingerprint_report(recorded: dict | None, here: dict) -> list[str]:
    """Lines that say how this host differs from the fingerprint recorded for its platform, compared fields and
    information alike (the commit and the paths of the build left out): what to read first when tier B or C fails,
    to tell a platform that moved from a change in the code."""
    if recorded is None:
        return [f"no fingerprint is recorded for platform {here['platform']!r}"]
    lines = ["compared field " + m for m in fingerprint_mismatch(recorded, here)]
    a, b = dict(recorded.get("informational", {})), dict(here.get("informational", {}))
    skip = ("git_sha", "git_dirty", "source_commit", "source_dirty", "library", "threads")
    for side in (a, b):
        side["build_info"] = {k: v for k, v in side.get("build_info", {}).items() if k not in skip}
    for k in sorted(set(a) | set(b)):
        if a.get(k) != b.get(k):
            lines.append(f"{k}: recorded {a.get(k)!r}, here {b.get(k)!r}")
    # What the record does not pin is named here rather than left to be read as "then it must be the code": the
    # fingerprint carries the hash of the dependency pins file of the source tree, not the identity of the installed
    # third-party prefix the build links, so a stack rebuilt or replaced at the same pinned versions moves the bytes
    # while every compared field still matches (docs/developer/g0.md).
    return lines or ["this host has the fingerprint recorded for its platform, the informational fields included (the "
                     "record pins the dependency versions of the source tree, not the installed third-party prefix: a "
                     "stack rebuilt at the same versions is a platform change this record cannot see)"]


