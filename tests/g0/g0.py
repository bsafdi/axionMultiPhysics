#!/usr/bin/env python3
"""G0, the compatibility gate: what an electromagnetic design observes of axionMultiPhysics, recorded and compared.

    python tests/g0/g0.py fingerprint              # print this platform's key and fingerprint
    python tests/g0/g0.py record  [--out DIR]      # record a baseline on this platform (docs/developer/g0.md)
    python tests/g0/g0.py check   [--tiers ABC]    # compare this build with the committed baseline
    python tests/g0/g0.py tolerances               # derive tests/g0/tolerances.json from the recorded platform spread
    python tests/g0/g0.py pending [--write]        # what a recorded platform has no record of, and why

Three tiers (docs/developer/g0.md):

  A  text, on every recorded platform: stdout and exit status of `axmp validate` and `axmp resolve`, the mesher's
     input file, and a corpus of invalid documents (stdout, exit status, and the Python exception's type, str and args).
  B  bytes, on the pinned reference platform (one node type of the development cluster) against its own record, while
     its fingerprint is the recorded one: the mesh files, results.json, scene.json, the status file, the names of the
     files and the exit status of the solves in the manifest's `tier_b` list, byte for byte outside its mask list.
     The reference platform's record is also the one the other platforms are compared with in tier C.
  C  physics, on every platform but the reference, against the reference platform's record: of results.json of the
     same solves, the scalar figures to a relative tolerance per quantity that is measured from the
     platform-to-platform spread (tests/g0/tolerances.json), and everything that is not a number (the verdicts of the
     physics checks, the strings, the keys in file order and the list lengths) exactly, outside the leaves that were
     measured to differ on that platform and are listed there.

Everything this script writes under tests/g0/baseline/ and tests/g0/spread/ is generated by `record`; nothing there is
edited by hand. Only the standard library and the built package are needed.
"""
