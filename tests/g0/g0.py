def python_validate(text: str, norm: Norm | None = None) -> dict:
    """What the binding `axionmultiphysics._core.validate` does with a document text: the result, or the exception's
    type, str and args (the file reading of `Design` and `axmp validate` are in the text streams)."""
    axmp = _import_package()
    n = norm or (lambda s: s)
    try:
        res = axmp._core.validate(text)
    except Exception as e:  # noqa: BLE001 - the type is the datum
        return {"exception": f"{type(e).__module__}.{type(e).__qualname__}", "str": n(str(e)),
                "args": [n(repr(a)) for a in e.args]}
    return {"ok": n(res if isinstance(res, str) else json.dumps(res))}


def tier_a_diff(base: dict, now: dict, masks: list[dict], where="tier A", no_record=()) -> list[str]:
    """Where the text streams of this run differ from the baseline. `no_record` names the entries this platform has no
    record of, which `check` reports as pending (it is empty on the reference platform, where pending is a failure)."""
    masked = {(m["entry"], m["op"], m["stream"]) for m in masks}
    diffs = []
    for section in ("designs", "corpus"):
        b, n = base[section], now[section]
        for k in sorted(set(b) | set(n)):
            if k not in b or k not in n:
                if k in n and (k if section == "designs" else f"corpus:{k}") in no_record:
                    continue  # listed as pending for this platform, with its reason (tests/g0/pending.json)
                diffs.append(f"{where}: {_what(section)} {k!r} is "
                             + ("not in the baseline (a new entry is pending until it is recorded on this platform: "
                                "docs/developer/g0.md)" if k in n else "in the baseline and was not run"))
                continue
            for op in sorted(set(b[k]) | set(n[k])):
                x, y = b[k].get(op), n[k].get(op)
                for stream in sorted(set(x or {}) | set(y or {})):
                    if (k, op, stream) in masked:
                        continue
                    if (x or {}).get(stream) != (y or {}).get(stream):
                        diffs.append(f"{where}: {_what(section)} {k!r} {op} {stream} differs\n" + _first_diff((x or {}).get(stream), (y or {}).get(stream)))
    return diffs


def _what(section: str) -> str:
    return "design" if section == "designs" else "corpus document"


def _first_diff(a, b) -> str:
    sa, sb = json.dumps(a, indent=1, sort_keys=True), json.dumps(b, indent=1, sort_keys=True)
    la, lb = sa.splitlines(), sb.splitlines()
    for i in range(max(len(la), len(lb))):
        x = la[i] if i < len(la) else "<end>"
        y = lb[i] if i < len(lb) else "<end>"
        if x != y:
            return f"    baseline: {x}\n    now:      {y}"
    return ""


def tier_a_masks(r1: dict, r2: dict) -> list[dict]:
    """Streams of tier A that differ between two runs on the same commit and platform (a mask entry each)."""
    masks = []
    for section in ("designs", "corpus"):
        for k in sorted(r1[section]):
            for op, a in r1[section][k].items():
                b = r2[section][k][op]
                for stream in sorted(set(a) | set(b)):
                    if a.get(stream) != b.get(stream):
                        why = _first_diff(a.get(stream), b.get(stream)).strip().replace("\n", " | ")
                        masks.append({"entry": k, "op": op, "stream": stream,
                                      "reason": "differs between two runs on this platform: " + why})
    return masks


