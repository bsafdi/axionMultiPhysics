    r.set_defaults(fn=cmd_record)
    c = sub.add_parser("check")
    c.add_argument("--tiers", default="ABC",
                   help="tiers to run (default ABC; B compares with the platform's own record, is refused where the "
                        "fingerprint is not the recorded one and is no part of the gate on a hosted-runner platform; C "
                        "compares with the reference platform's record and does not run on the reference platform itself)")
    c.add_argument("--baseline-platform", help="compare tier A with another platform's baseline (a host of its own)")
    c.add_argument("--only", help="comma-separated tier-B/C entry ids")
