"""Print docs/reference/error_codes.md, the reference page of the codes of a model document's findings.

    python scripts/docs/gen_error_codes.py > docs/reference/error_codes.md

The page is generated from ``axionmultiphysics._core.error_codes()``, the table of codes of the model path
(``cpp/src/model_errors.hpp``), so it needs the compiled core. The output is deterministic;
``tests/test_error_codes_doc.py`` fails when the committed page differs from it. Do not edit the page by hand: change
the table and regenerate.
"""
from __future__ import annotations

import json
import sys

AREAS = {
    "boundary": "Boundaries and selectors",
    "coupling": "Couplings",
    "domain": "Domains",
    "electrochem": "Electrochemistry",
    "expr": "Expressions",
    "fluid": "Flow",
    "geometry": "Geometry",
    "heat": "Heat transfer",
    "internal": "Internal",
    "json": "The file",
    "law": "Property laws",
    "material": "Materials",
    "mesh": "Mesh",
    "model": "The document",
    "output": "Outputs",
    "patch": "Patch",
    "physics": "Physics instances",
    "reaction": "Reactions",
    "route": "Routes",
    "study": "Study",
}


def esc(text) -> str:
    """Text for a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def page(table: list) -> str:
    out = ["# Error codes of the model document (beta)", ""]
    out.append("<!-- Generated by scripts/docs/gen_error_codes.py from axionmultiphysics._core.error_codes(); do not edit by "
               "hand. -->")
    out.append("")
    out.append(
        "Most findings about a model document (a design with a `physics` section) carry a `code`: a stable identifier "
        "of the form `area.problem`, for programs and assistants to act on, beside the message, the JSON pointer and the "
        "hint that people read. This page lists every code of the model path. A few findings carry no code, and for them "
        "the message, the pointer and the hint are all there is: the ones that an electromagnetic design can also have (a "
        "required field that is missing, a field that does not exist, a value of the wrong type or out of its range), an "
        "expression that cannot be read or evaluated, an unknown value of `symmetry`, of a study `type`, of a coupling "
        "`strategy` or of a continuation `scale`, and an internal failure of the validation. Model documents are "
        "**beta**: this version validates a model document (`axmp validate`, `Design.validate()`), resolves its geometry "
        "(`axmp resolve`), explains it (`axmp explain`), patches it (`axmp patch`), lists and checks its named boundaries "
        "(`axmp boundaries`) and meshes a planar or axisymmetric one (`axmp mesh`, `axmp.mesh`); it solves none (no route is "
        "implemented), so a code may still be renamed. Some codes are raised for electromagnetic designs too: "
        "`model.section_needs_physics` (a section of a model document in a design without `physics`), the refusals of an "
        "`arc` path (`geometry.arc_span`, `geometry.arc_degenerate`, `geometry.arc_negative_r`) and `mesh.tangled`, when "
        "a 2D mesh with a tangled curved element is read.")
    out.append("")
    out.append("A finding has one of four kinds:")
    out.append("")
    out.append("| kind | meaning |")
    out.append("|---|---|")
    out.append("| error | The document is wrong, and is refused. |")
    out.append("| unavailable | The document is valid; this version or this build cannot solve it. |")
    out.append("| deferred | A check that needs the resolved geometry or an imported mesh file, and runs when that is built or read. |")
    out.append("| warning | The document is valid; something about it is worth knowing. |")
    out.append("")
    raised = [e for e in table if e["status"] == "raised"]
    reserved = [e for e in table if e["status"] != "raised"]
    out.append(f"This version raises {len(raised)} codes and names {len(reserved)} more that a later version raises. The "
               "types, coupling terms and routes that the codes refer to are in the "
               "[physics catalogue](physics_catalogue.md).")
    out.append("")
    areas = sorted({e["code"].split(".")[0] for e in raised}, key=lambda a: AREAS.get(a, a).lower())
    for area in areas:
        out.append(f"## {AREAS.get(area, area)} (`{area}`)")
        out.append("")
        out.append("| code | kind | raised for |")
        out.append("|---|---|---|")
        for e in raised:
            if e["code"].split(".")[0] == area:
                out.append(f"| `{e['code']}` | {', '.join(e['kinds'])} | {esc(e['summary'])} |")
        out.append("")
    if reserved:
        out.append("## Reserved")
        out.append("")
        out.append("Codes that this version names, in the route table, in the details of a deferred finding or in the check on "
                   "the resolved boundaries that a later version runs, and that no path of this version raises.")
        out.append("")
        out.append("| code | kind | meaning |")
        out.append("|---|---|---|")
        for e in reserved:
            out.append(f"| `{e['code']}` | {', '.join(e['kinds'])} | {esc(e['summary'])} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    from axionmultiphysics import _core
    sys.stdout.write(page(json.loads(_core.error_codes())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
